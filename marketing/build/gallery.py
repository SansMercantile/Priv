"""Generate 03-POSTER-GALLERY.md from the rendered poster files."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import poster_specs  # noqa: E402
import posters  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "03-POSTER-GALLERY.md")
PO = os.path.join(ROOT, "assets", "posters")

FORMAT_LABEL = {
    "feed": ("Feed / square-ish", "1080 x 1350"),
    "story": ("Story / Reel / TikTok", "1080 x 1920"),
    "wide": ("Landscape / header", "1920 x 1080"),
    "link": ("Link card / OG", "1200 x 630"),
    "thumb": ("Video thumbnail", "1280 x 720"),
}


def human(n):
    return f"{n / 1024:.0f} KB"


def main():
    rows = []
    total = 0
    lines = []
    lines.append("# 03 — Poster gallery")
    lines.append("")
    lines.append("_Auto-generated by `build/gallery.py`. Do not edit by hand._")
    lines.append("")
    lines.append("Every design is rendered through one compositor "
                 "(`build/posters.py`) against one spec table "
                 "(`build/poster_specs.py`), so the type scale, margins, scrim "
                 "and footer are identical across all 38 files. The layout "
                 "audit (`build/audit.py`) asserts that no headline, sub-head, "
                 "body block, CTA or footer overlaps and that nothing overflows "
                 "its vertical budget — it prints `ALL CLEAR` on the current set.")
    lines.append("")
    lines.append("## Formats")
    lines.append("")
    lines.append("| Format | Use | Size |")
    lines.append("| --- | --- | --- |")
    for k, (use, size) in FORMAT_LABEL.items():
        lines.append(f"| `{k}` | {use} | {size} |")
    lines.append("")

    for slug, spec in poster_specs.POSTERS.items():
        lines.append(f"### `{slug}`")
        lines.append("")
        lines.append(f"**{spec['headline']}**  ")
        lines.append(f"_{spec['sub']}_" if spec.get("sub") else "")
        lines.append("")
        lines.append(f"- Eyebrow: `{spec['eyebrow']}`")
        lines.append(f"- Plate: `assets/backgrounds/{spec['plate']}.jpg`")
        lines.append(f"- Body: `{spec['body']['kind']}`")
        if spec.get("cta"):
            lines.append(f"- CTA: {spec['cta']}")
        if spec.get("body_well"):
            lines.append("- Soft content well + deeper bottom scrim (bright plate)")
        lines.append("")
        lines.append("| Format | File | Size |")
        lines.append("| --- | --- | --- |")
        for fmt in spec["formats"]:
            name = f"priv-{slug}-{fmt}.jpg"
            path = os.path.join(PO, fmt, name)
            if not os.path.exists(path):
                lines.append(f"| `{fmt}` | _MISSING_ | — |")
                continue
            size = os.path.getsize(path)
            total += 1
            w, h = posters.FORMATS[fmt]
            lines.append(f"| `{fmt}` ({w}x{h}) | `{os.path.relpath(path, ROOT).replace(os.sep, '/')}` | {human(size)} |")
        lines.append("")
        rows.append(slug)

    lines.insert(5, f"\n**{total} files** across {len(rows)} designs.\n")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({total} files, {len(rows)} designs)")


if __name__ == "__main__":
    main()
